/**
 * Finish an `expo export --platform web` so GitHub Pages can host it.
 *
 * Copies feed/ to dist/feed, adds the SPA fallback and .nojekyll, and checks
 * that JavaScript URLs include the project subpath.
 *
 * Usage: node scripts/prepare-pages.mjs
 */
import { copyFile, cp, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const basePath = '/mormon-news-roundup';
const tagline = 'Your Daily Mormon News: Unfiltered';

const indexPath = path.join(dist, 'index.html');
let html = await readFile(indexPath, 'utf8');

if (!html.includes(`${basePath}/_expo/`)) {
  console.error(
    `dist/index.html does not reference ${basePath}/_expo/. ` +
      'Set expo.experiments.baseUrl in app.json to that path and export again.',
  );
  process.exit(1);
}

function upsertMeta(source, attribute, key, content) {
  const tag = `<meta ${attribute}="${key}" content="${content}" />`;
  const pattern = new RegExp(`<meta\\s+${attribute}="${key}"\\s+content="[^"]*"\\s*/?>`, 'i');
  if (pattern.test(source)) return source.replace(pattern, tag);
  return source.replace('</head>', `    ${tag}\n</head>`);
}

if (!html.includes('apple-mobile-web-app-capable')) {
  const tags = `
    <meta name="theme-color" content="#1D1838" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-title" content="Mormon News" />
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
    <link rel="manifest" href="${basePath}/manifest.webmanifest" />
    <link rel="apple-touch-icon" href="${basePath}/apple-touch-icon.png" />
`;
  html = html.replace('</head>', `${tags}</head>`);
}

html = upsertMeta(html, 'name', 'description', tagline);
html = upsertMeta(html, 'property', 'og:title', 'Mormon News Roundup');
html = upsertMeta(html, 'property', 'og:description', tagline);
html = upsertMeta(html, 'name', 'twitter:card', 'summary');
html = upsertMeta(html, 'name', 'twitter:description', tagline);

// GitHub Pages keeps index.html for about 10 minutes. A service worker
// answers document requests from the network first, so a cached shell cannot
// hide a new deploy. The page script still reloads when the hashed bundles change.
const shellCheck = `
<script>
(function () {
  var base = ${JSON.stringify(basePath)};
  if ('serviceWorker' in navigator) {
    navigator.serviceWorker.register(base + '/sw.js', { scope: base + '/', updateViaCache: 'none' }).catch(function () {});
  }
  var storageKey = 'mnr.shell.bundle';
  function bundles(source) {
    return (String(source).match(/\\/_expo\\/static\\/js\\/web\\/[^"'\\s>]+\\.js/g) || []).sort().join('\\n');
  }
  function check() {
    var current = bundles(document.documentElement.innerHTML);
    if (!current) return;
    var page = location.pathname;
    if (page.endsWith('/index.html')) page = page.slice(0, -'index.html'.length);
    if (!page.endsWith('/')) page += '/';
    fetch(page + '?fresh=' + Date.now(), { cache: 'no-store' })
      .then(function (response) { return response.text(); })
      .then(function (nextHtml) {
        var next = bundles(nextHtml);
        if (!next || next === current) {
          try { sessionStorage.removeItem(storageKey); } catch (err) {}
          return;
        }
        try {
          if (sessionStorage.getItem(storageKey) === next) return;
          sessionStorage.setItem(storageKey, next);
        } catch (err) {}
        var dest = new URL(location.href);
        dest.searchParams.set('v', String(Date.now()));
        location.replace(dest.toString());
      })
      .catch(function () {});
  }
  check();
  document.addEventListener('visibilitychange', function () {
    if (document.visibilityState === 'visible') check();
  });
})();
</script>
`;
if (!html.includes('mnr.shell.bundle')) {
  html = html.replace('</body>', `${shellCheck}</body>`);
}

await writeFile(indexPath, html);

// Document requests only. Hashed scripts and the feed stay on the normal cache.
const serviceWorker = `/* Network-first HTML for ${basePath}. Generated by scripts/prepare-pages.mjs. */
self.addEventListener('install', function (event) {
  event.waitUntil(self.skipWaiting());
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(
        keys.filter(function (key) { return key.indexOf('mnr-shell') === 0; }).map(function (key) {
          return caches.delete(key);
        }),
      );
    }).then(function () {
      return self.clients.claim();
    }),
  );
});

var BASE = ${JSON.stringify(basePath)};

function isAppHtml(request) {
  if (request.method !== 'GET') return false;
  var url;
  try {
    url = new URL(request.url);
  } catch (err) {
    return false;
  }
  if (url.origin !== self.location.origin) return false;
  if (url.pathname.indexOf(BASE) !== 0) return false;
  if (request.mode === 'navigate' || request.destination === 'document') return true;
  var path = url.pathname.slice(BASE.length);
  return path === '' || path === '/' || path.endsWith('.html');
}

self.addEventListener('fetch', function (event) {
  if (!isAppHtml(event.request)) return;
  event.respondWith(
    fetch(event.request, { cache: 'no-store' }).catch(function () {
      return fetch(event.request);
    }),
  );
});
`;
await writeFile(path.join(dist, 'sw.js'), serviceWorker);

// feed/ is the public edition, including feed/images/. fallback/ stays out.
await cp(path.join(root, 'feed'), path.join(dist, 'feed'), { recursive: true });

async function filesUnder(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await filesUnder(full)));
    else files.push(full);
  }
  return files;
}

const imageRoot = path.join(root, 'feed', 'images');
let imageCount = 0;
try {
  const images = await filesUnder(imageRoot);
  imageCount = images.length;
  for (const file of images) {
    const rel = path.relative(path.join(root, 'feed'), file);
    const dest = path.join(dist, 'feed', rel);
    try {
      await readFile(dest);
    } catch {
      console.error(`Feed image was not copied to dist/feed/${rel}`);
      process.exit(1);
    }
  }
} catch (error) {
  if (error?.code !== 'ENOENT') throw error;
}
await copyFile(indexPath, path.join(dist, '404.html'));
await writeFile(path.join(dist, '.nojekyll'), '');

const feedIndex = JSON.parse(await readFile(path.join(dist, 'feed', 'index.json'), 'utf8'));
if (!Array.isArray(feedIndex.days) || feedIndex.days.length === 0) {
  console.error('dist/feed/index.json has no days.');
  process.exit(1);
}

console.log(`Pages bundle ready. Feed days: ${feedIndex.days.join(', ')}. Feed images: ${imageCount}`);
